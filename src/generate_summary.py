#!/usr/bin/env python3
"""
Post-Processing & Summary Generator
Group 9 - BDA Mini-Project

Reads the output/results.txt generated by the MapReduce reducer,
prints ASCII charts to terminal, and creates graphical plots if matplotlib is installed.
"""

import os
import sys

def generate_summary():
    project_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    results_path = os.path.join(project_root, "output", "results.txt")
    summary_md_path = os.path.join(project_root, "output", "summary_report.md")

    if not os.path.exists(results_path):
        print(f"Error: {results_path} not found. Run the MapReduce job first.")
        return

    routes = []
    trips = []
    passengers = []
    avg_passengers = []
    avg_delays = []

    with open(results_path, "r", encoding="utf-8") as f:
        lines = f.readlines()
        for line in lines[1:]:  # skip header
            parts = line.strip().split("\t")
            if len(parts) >= 5:
                routes.append(parts[0])
                trips.append(int(parts[1]))
                passengers.append(int(parts[2]))
                avg_passengers.append(float(parts[3]))
                avg_delays.append(float(parts[4]))

    if not routes:
        print("No valid records found in results.")
        return

    print("\n=======================================================")
    print("      PUBLIC TRANSPORTATION ANALYSIS: SUMMARY          ")
    print("=======================================================")

    # ASCII Chart: Total Passengers by Route
    max_p = max(passengers) if passengers else 1
    print("\n[Chart 1] Total Commuter Volume by Route:")
    print("-" * 55)
    for r, p in zip(routes, passengers):
        bar_len = int((p / max_p) * 30)
        bar = "#" * bar_len
        print(f"{r:<11} | {bar:<30} {p:>4} passengers")

    # ASCII Chart: Average Delay (Minutes) by Route
    max_d = max(avg_delays) if avg_delays else 1
    print("\n[Chart 2] Average Delay (Minutes) by Route:")
    print("-" * 55)
    for r, d in zip(routes, avg_delays):
        bar_len = int((d / max_d) * 30)
        bar = "=" * bar_len
        print(f"{r:<11} | {bar:<30} {d:>5.2f} mins")

    print("=======================================================\n")

    # Save summary report as Markdown
    busiest_route = routes[passengers.index(max(passengers))]
    most_delayed_route = routes[avg_delays.index(max(avg_delays))]

    md_content = f"""# Public Transportation Analysis - Executive Summary
**Group 9 | Big Data Analytics (Hadoop & MapReduce)**

## Key Findings
- **Busiest Transit Corridor:** `{busiest_route}` with **{max(passengers)}** total commuters.
- **Most Delayed Route:** `{most_delayed_route}` with an average delay of **{max(avg_delays):.2f} minutes**.
- **Most Reliable Route:** `{routes[avg_delays.index(min(avg_delays))]}` with only **{min(avg_delays):.2f} minutes** average delay.

## Route-wise Metrics Table
| Route ID | Total Trips | Total Passengers | Avg Passengers/Trip | Avg Delay (Min) |
| :--- | :--- | :--- | :--- | :--- |
"""
    for r, t, p, ap, ad in zip(routes, trips, passengers, avg_passengers, avg_delays):
        md_content += f"| {r} | {t} | {p} | {ap:.2f} | {ad:.2f} |\n"

    with open(summary_md_path, "w", encoding="utf-8") as f_out:
        f_out.write(md_content)

    print(f"Summary markdown generated at: output/summary_report.md")

    # Attempt to plot with matplotlib if user has it installed
    try:
        import matplotlib.pyplot as plt
        fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 5))

        # Passengers Plot
        ax1.bar(routes, passengers, color="#2b5c8f")
        ax1.set_title("Total Passengers per Route")
        ax1.set_xlabel("Route")
        ax1.set_ylabel("Passenger Count")
        ax1.tick_params(axis='x', rotation=30)

        # Delays Plot
        ax2.bar(routes, avg_delays, color="#d9534f")
        ax2.set_title("Average Delay (Minutes)")
        ax2.set_xlabel("Route")
        ax2.set_ylabel("Delay (Minutes)")
        ax2.tick_params(axis='x', rotation=30)

        plt.tight_layout()
        plot_path = os.path.join(project_root, "output", "transit_analysis_charts.png")
        plt.savefig(plot_path, dpi=200)
        print(f"Graphical charts saved at: output/transit_analysis_charts.png")
    except ImportError:
        print("(Note: Install 'matplotlib' if you want exported PNG charts: pip install matplotlib)")

if __name__ == "__main__":
    generate_summary()
